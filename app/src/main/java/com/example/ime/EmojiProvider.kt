            Category.RECENTS -> emptyList() // Resolved dynamically from RecentEmojiManager
            Category.SMILEYS -> SMILEYS
            Category.SAD -> SAD_AND_EMOTIONAL
            Category.GESTURES -> GESTURES_AND_PEOPLE
            Category.ANIMALS -> ANIMALS_AND_NATURE
            Category.FOOD -> FOOD_AND_DRINK
            Category.TRAVEL -> TRAVEL_AND_PLACES
            Category.ACTIVITIES -> ACTIVITIES
            Category.OBJECTS -> OBJECTS
            Category.SYMBOLS -> SYMBOLS
            Category.FLAGS -> FLAGS
        }
    }

    /**
     * Returns all available categories for the tab bar.
     */
    fun getCategories(): List<Category> {
        return Category.values().toList()
    }
